const norm = (s: string) => s.toLowerCase().replace(/ё/g, "е").replace(/[^\p{L}\p{N}+]+/gu, " ").trim();
// crude Russian stemming: compare word prefixes
const stem = (w: string) => (w.length > 5 ? w.slice(0, w.length - 2) : w);

export function searchKnowledge(query: string, limit = 3) {
  const words = norm(query).split(" ").filter((w) => w.length > 2).map(stem);
  if (!words.length) return [];
  return ARTICLES.map((a) => {
    const hay = norm(`${a.title} ${a.tags.join(" ")} ${a.body}`);
    const tags = norm(`${a.title} ${a.tags.join(" ")}`);
    let score = 0;
    for (const w of words) {
      if (tags.includes(w)) score += 3;
      else if (hay.includes(w)) score += 1;
    }
    return { a, score };
  })
    .filter((x) => x.score > 0)
    .sort((x, y) => y.score - x.score)
    .slice(0, limit)
    .map(({ a }) => ({ id: a.id, title: a.title, body: a.body }));
}
